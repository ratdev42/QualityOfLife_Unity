using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Security;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

namespace EnumForge
{
    public static class EnumCodeGenerator
    {
        const string Marker = "Generated by EnumForge";

        static readonly Regex IdentifierRegex = new (@"^[A-Za-z_][A-Za-z0-9_]*$");

        static readonly HashSet<string> Keywords = new ()
        {
            "abstract","as","base","bool","break","byte","case","catch","char","checked","class",
            "const","continue","decimal","default","delegate","do","double","else","enum","event",
            "explicit","extern","false","finally","fixed","float","for","foreach","goto","if",
            "implicit","in","int","interface","internal","is","lock","long","namespace","new","null",
            "object","operator","out","override","params","private","protected","public","readonly",
            "ref","return","sbyte","sealed","short","sizeof","stackalloc","static","string","struct",
            "switch","this","throw","true","try","typeof","uint","ulong","unchecked","unsafe",
            "ushort","using","virtual","void","volatile","while"
        };

        public static bool IsValidIdentifier(string value)
        {
            return !string.IsNullOrEmpty(value) && IdentifierRegex.IsMatch(value) && !Keywords.Contains(value);
        }

        /// <summary>"fire ball-2" -> "FireBall2", "3d" -> "_3d"</summary>
        public static string Sanitize(string raw)
        {
            if (string.IsNullOrWhiteSpace(raw))
            {
                return string.Empty;
            }

            StringBuilder builder = new ();
            foreach (string part in Regex.Split(raw.Trim(), @"[^A-Za-z0-9_]+").Where(p => p.Length > 0))
            {
                builder.Append(char.ToUpperInvariant(part[0])).Append(part.Substring(1));
            }

            string result = builder.ToString();
            if (result.Length > 0 && char.IsDigit(result[0]))
            {
                result = "_" + result;
            }

            return result;
        }

        public static List<string> Validate(EnumDefinition enumDefinition)
        {
            List<string> errors = new ();

            if (!IsValidIdentifier(enumDefinition.name))
            {
                errors.Add($"Enum name '{enumDefinition.name}' is not a valid C# identifier.");
            }

            string folderPath = (enumDefinition.outputFolderPath ?? "").Replace('\\', '/');

            if (folderPath != "Assets" && !folderPath.StartsWith("Assets/"))
            {
                errors.Add("Output folder must be inside Assets/.");
            }

            HashSet<string> names = new ();
            HashSet<int> values = new ();

            for (int i = 0; i < enumDefinition.entries.Count; i++)
            {
                EnumDefinition.Entry entry = enumDefinition.entries[i];

                if (!IsValidIdentifier(entry.name))
                {
                    errors.Add($"Entry #{i}: '{entry.name}' is not a valid C# identifier.");
                }
                else if (!names.Add(entry.name))
                {
                    errors.Add($"Duplicate entry name '{entry.name}'.");
                }

                if (!values.Add(entry.value))
                {
                    errors.Add($"Entry '{entry.name}' has duplicate value {entry.value}.");
                }

                if (enumDefinition.isMask)
                {
                    if (entry.name == "None")
                    {
                        errors.Add("'None' is reserved in Flags enums (generated automatically as 0).");
                    }
                    if (entry.value < 0 || entry.value > 31)
                    {
                        errors.Add($"'{entry.name}' uses bit {entry.value}; Flags enums support bits 0-31.");
                    }
                }
            }

            return errors;
        }

        static readonly string indentation = "    ";
            
        public static string BuildSource(EnumDefinition enumDefinition)
        {
            StringBuilder builder = new ();
            builder.AppendLine("// <auto-generated>");
            builder.AppendLine($"// {Marker} from {AssetDatabase.GetAssetPath(enumDefinition)}");
            builder.AppendLine("// Do not edit by hand: edit the EnumDefinition asset and click Generate.");
            builder.AppendLine("// </auto-generated>");
            builder.AppendLine();

            if (enumDefinition.isMask) builder.AppendLine($"{indentation}[System.Flags]");

            builder.AppendLine($"public enum {enumDefinition.name}");
            builder.AppendLine($"{{");

            if (enumDefinition.isMask) builder.AppendLine($"{indentation}None = 0,");

            foreach (EnumDefinition.Entry entry in enumDefinition.entries)
            {
                string value = enumDefinition.isMask ? $"1 << {entry.value}" : entry.value.ToString();
                builder.AppendLine($"{indentation}{entry.name} = {value},");
            }

            builder.AppendLine($"}}");
            return builder.ToString();
        }

        public static bool IsUpToDate(EnumDefinition enumDefinition)
        {
            string path = enumDefinition.OutputPath;
            return File.Exists(path) && File.ReadAllText(path) == BuildSource(enumDefinition);
        }

        static bool IsOurs(string path) => File.ReadAllText(path).Contains(Marker);

        public static bool Generate(EnumDefinition enumDefinition)
        {
            List<string> errors = Validate(enumDefinition);

            if (errors.Count > 0)
            {
                Debug.LogError($"[EnumForge] Cannot generate '{enumDefinition.name}':\n- " + string.Join("\n- ", errors), enumDefinition);
                return false;
            }

            string path = enumDefinition.OutputPath;
            string source = BuildSource(enumDefinition);

            // Never overwrite a hand-written file that happens to share the name.
            if (File.Exists(path) && !IsOurs(path))
            {
                Debug.LogError($"[EnumForge] {path} exists and was not generated by EnumForge. Refusing to overwrite.", enumDefinition);
                return false;
            }

            // Enum was renamed or moved: remove the previously generated file.
            string oldPath = enumDefinition.lastGeneratedPath;
            if (!string.IsNullOrEmpty(oldPath) && oldPath != path && File.Exists(oldPath) && IsOurs(oldPath))
            {
                AssetDatabase.DeleteAsset(oldPath);
            }

            if (!File.Exists(path) || File.ReadAllText(path) != source)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(path));
                File.WriteAllText(path, source);
                AssetDatabase.ImportAsset(path); // triggers recompilation
            }

            if (enumDefinition.lastGeneratedPath != path)
            {
                enumDefinition.lastGeneratedPath = path;
                EditorUtility.SetDirty(enumDefinition);
                AssetDatabase.SaveAssetIfDirty(enumDefinition);
            }

            Debug.Log($"[EnumForge] Generated {path}", enumDefinition);
            return true;
        }

        [MenuItem("Tools/EnumForge/Regenerate All")]
        static void RegenerateAll()
        {
            AssetDatabase.StartAssetEditing(); // batch imports => a single recompile
            try
            {
                foreach (string guid in AssetDatabase.FindAssets("t:" + nameof(EnumDefinition)))
                {
                    EnumDefinition def = AssetDatabase.LoadAssetAtPath<EnumDefinition>(AssetDatabase.GUIDToAssetPath(guid));

                    if (def != null)
                    {
                        Generate(def);
                    }
                }
            }
            finally
            {
                AssetDatabase.StopAssetEditing();
            }
        }
    }
}
